package de.billery.repository;

import static de.billery.data.DatabaseUtils.emptyToNull;
import static de.billery.data.DatabaseUtils.nullToEmpty;

import de.billery.api.dto.SearchResult.SearchArticle;
import de.billery.data.Article;
import java.util.Collection;
import java.util.List;
import org.springframework.jdbc.core.RowMapper;
import org.springframework.jdbc.core.simple.JdbcClient;
import org.springframework.jdbc.support.GeneratedKeyHolder;
import org.springframework.jdbc.support.KeyHolder;
import org.springframework.stereotype.Repository;

/**
 * Repository class for managing Article entities in the database. Extends BaseRepository to inherit
 * common logging and error handling functionality.
 *
 * <p>This repository provides CRUD operations for article data including:
 *
 * <ul>
 *   <li>Finding all articles or individual articles by ID
 *   <li>Saving new articles to the database
 *   <li>Updating existing article information
 *   <li>Deleting articles from the database
 * </ul>
 *
 * <p>All statements run through the shared {@link JdbcClient}, so they join the caller's
 * transaction; database errors surface as {@code DatabaseException} (see {@link BaseRepository}).
 * The article's {@code note} is an internal remark; it is stored but never printed.
 *
 * @author Invoice Management System
 * @version 1.0
 */
@Repository
public class ArticleRepository extends BaseRepository {

  /** Maps an {@code article} row; a NULL purchase value becomes 0. */
  private static final RowMapper<Article> ARTICLE_MAPPER =
      (rs, rowNum) -> {
        Article article =
            new Article(
                rs.getInt("id"),
                rs.getString("article_name"),
                decimalOrZero(rs, "purchase_value"),
                decimalOrZero(rs, "sales_value"),
                nullToEmpty(rs.getString("unit")),
                nullToEmpty(rs.getString("note")),
                nullToEmpty(rs.getString("article_description")));
        article.setTaxRatePercent(decimalOrZero(rs, "tax_rate_percent"));
        return article;
      };

  /** Maps an {@code article} row to a search hit. */
  private static final RowMapper<SearchArticle> SEARCH_MAPPER =
      (rs, rowNum) ->
          new SearchArticle(
              rs.getInt("id"),
              nullToEmpty(rs.getString("article_name")),
              decimalOrZero(rs, "purchase_value"),
              decimalOrZero(rs, "sales_value"),
              nullToEmpty(rs.getString("unit")),
              nullToEmpty(rs.getString("article_description")));

  private final JdbcClient jdbc;

  /**
   * Creates the repository.
   *
   * @param jdbc the shared JdbcClient
   */
  public ArticleRepository(JdbcClient jdbc) {
    super();
    this.jdbc = jdbc;
  }

  /**
   * Retrieves all articles ordered by id, so the catalog keeps its order when an article is edited
   * (without an {@code ORDER BY}, PostgreSQL returns an updated row wherever its new version lies,
   * usually at the end).
   *
   * @return a list of all articles, or an empty list if none exist
   */
  public List<Article> findAll() {
    return run(
        "findAll articles",
        () -> jdbc.sql("SELECT * FROM article ORDER BY id").query(ARTICLE_MAPPER).list());
  }

  /**
   * The articles with the given ids (the articles sold in a statistics period).
   *
   * @param ids the article ids
   * @return the articles found; unknown ids are absent
   */
  public List<Article> findByIds(Collection<Integer> ids) {
    if (ids.isEmpty()) {
      return List.of();
    }
    return run(
        "findByIds articles",
        () ->
            jdbc.sql("SELECT * FROM article WHERE id IN (:ids)")
                .param("ids", ids)
                .query(ARTICLE_MAPPER)
                .list());
  }

  /**
   * Saves a new article to the database. The article's ID is generated by the database and set on
   * the passed object.
   *
   * @param article the article to save
   * @return the same article, now carrying its ID
   */
  public Article save(Article article) {
    return run(
        "save article",
        () -> {
          KeyHolder keys = new GeneratedKeyHolder();
          bind(
                  jdbc.sql(
                      """
                      INSERT INTO article (article_name, purchase_value, sales_value, unit,
                                           article_description, note, tax_rate_percent)
                      VALUES (:name, :purchaseValue, :salesValue, :unit, :description, :note,
                              :taxRate)
                      """),
                  article)
              .update(keys);
          article.setId(generatedId(keys));
          return article;
        });
  }

  /**
   * Updates an existing article in the database. The article is identified by its ID and all fields
   * are updated.
   *
   * @param article the article with updated information
   */
  public void update(Article article) {
    run(
        "update article",
        () ->
            bind(
                    jdbc.sql(
                        """
                        UPDATE article SET article_name = :name, purchase_value = :purchaseValue,
                                           sales_value = :salesValue, unit = :unit,
                                           article_description = :description, note = :note,
                                           tax_rate_percent = :taxRate
                        WHERE id = :id
                        """),
                    article)
                .param("id", article.getId())
                .update());
  }

  /**
   * Deletes an article from the database by ID.
   *
   * @param articleId the ID of the article to delete
   */
  public void delete(int articleId) {
    run(
        "delete article",
        () -> jdbc.sql("DELETE FROM article WHERE id = :id").param("id", articleId).update());
  }

  /**
   * Finds an article by its unique ID.
   *
   * @param id the ID of the article to find
   * @return the article if found, null otherwise
   */
  public Article findById(int id) {
    return run(
        "findById article",
        () ->
            jdbc.sql("SELECT * FROM article WHERE id = :id")
                .param("id", id)
                .query(ARTICLE_MAPPER)
                .optional()
                .orElse(null));
  }

  /**
   * Searches articles by id, name, description and prices, case-insensitively, against the raw
   * query and a variant with umlauts and ß transliterated.
   *
   * @param query the user's search text
   * @return up to 50 matches ordered by name
   */
  public List<SearchArticle> search(String query) {
    String normalizedQuery =
        query
            .replace("ä", "a")
            .replace("ö", "o")
            .replace("ü", "u")
            .replace("Ä", "A")
            .replace("Ö", "O")
            .replace("Ü", "U")
            .replace("ß", "ss");
    String sql =
        """
        SELECT * FROM article
        WHERE CAST(id AS VARCHAR(50)) LIKE :pattern
           OR LOWER(article_name) LIKE LOWER(:pattern)
           OR LOWER(article_description) LIKE LOWER(:pattern)
           OR CAST(purchase_value AS VARCHAR(50)) LIKE :pattern OR CAST(sales_value AS VARCHAR(50)) LIKE :pattern
           OR LOWER(article_name) LIKE LOWER(:normalized)
           OR LOWER(article_description) LIKE LOWER(:normalized)
           OR CAST(purchase_value AS VARCHAR(50)) LIKE :normalized
           OR CAST(sales_value AS VARCHAR(50)) LIKE :normalized
        ORDER BY article_name
        LIMIT 50
        """;
    return run(
        "search articles",
        () ->
            jdbc.sql(sql)
                .param("pattern", "%" + query + "%")
                .param("normalized", "%" + normalizedQuery + "%")
                .query(SEARCH_MAPPER)
                .list());
  }

  /** Binds the article's column values (empty strings stored as NULL). */
  private static JdbcClient.StatementSpec bind(JdbcClient.StatementSpec spec, Article article) {
    return spec.param("name", emptyToNull(article.getName()))
        .param("purchaseValue", article.getPurchaseValue())
        .param("salesValue", article.getSalesValue())
        .param("unit", emptyToNull(article.getUnit()))
        .param("description", emptyToNull(article.getDescription()))
        .param("note", emptyToNull(article.getNote()))
        .param("taxRate", article.getTaxRatePercent());
  }
}
