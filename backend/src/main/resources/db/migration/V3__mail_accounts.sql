-- ============================================================================
-- V3: the company's own SMTP accounts for sending documents to customers (#13)
-- ============================================================================
--
-- One row per account a company sends its invoices and offers with. The system account of the
-- operator (MAIL_*) is not here: it only sends system mails (invitations) and is configured in the
-- environment. The password is stored encrypted (AES-256-GCM, mail.CredentialCipher); the key is
-- outside the database (BILLERY_SECRETS_KEY, or a key file next to the desktop database), so a copy
-- of the database or a backup alone does not reveal it. The API never returns it.
--
-- Mail contents are not stored: a dispatch is recorded in document_history (recipients, subject,
-- account, attachments).
-- ============================================================================

CREATE TABLE mail_account (
    id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id INT NOT NULL DEFAULT 1,
    name VARCHAR(100) NOT NULL,
    host VARCHAR(255) NOT NULL,
    port INT NOT NULL CHECK (port BETWEEN 1 AND 65535),
    security VARCHAR(10) NOT NULL CHECK (security IN ('STARTTLS', 'SSL', 'NONE')),
    username VARCHAR(255),
    password_encrypted TEXT,
    from_address VARCHAR(255) NOT NULL,
    from_name VARCHAR(255),
    is_default SMALLINT NOT NULL DEFAULT 0 CHECK (is_default IN (0, 1)),
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_mail_account_tenant_id UNIQUE (tenant_id, id)
);

-- At most one default account per company (the application keeps it so as well; H2 has no
-- partial index).
CREATE UNIQUE INDEX uq_mail_account_default ON mail_account (tenant_id) WHERE is_default = 1;

CREATE TRIGGER trg_mail_account_updated_at BEFORE UPDATE ON mail_account
    FOR EACH ROW EXECUTE FUNCTION set_updated_at();
